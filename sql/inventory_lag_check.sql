-- 目的: NE_InventoryHistory におけるLAG関数を用いた在庫前後比較の検証
-- 作成日: 2026-06-28
-- 完了条件: 単一商品・複数商品での意図した挙動確認、およびインデックスなし状態のコスト計測
-- =================================================================

-- [ステップ1] 単一商品コードでの動作確認用クエリ
SELECT 
    "商品コード", 
    "記録日時", 
    "在庫数",
    LAG("在庫数") OVER (PARTITION BY "商品コード" ORDER BY "記録日時" ASC) AS "在庫数_前回"
FROM 
    "NE_InventoryHistory"
WHERE 
    "商品コード" = 'A001'
ORDER BY 
    "記録日時" ASC;