-- =================================================================
-- ファイル名: sql/inventory_lag_check.sql
-- 目的: NE_InventoryHistory におけるLAG関数を用いた在庫前後比較の検証
-- 変更履歴:
--   2026-06-28: 新規作成（単一商品、フリー在庫、JST変換追加）
--   2026-06-28: 複数商品対応（PARTITION BY のリセット挙動検証を追加）
-- =================================================================

SELECT 
    "商品コード", 
    "記録日時" AT TIME ZONE 'Asia/Tokyo' AS "記録日時_JST", 
    "在庫数",
    LAG("在庫数") OVER (
        PARTITION BY "商品コード" 
        ORDER BY "記録日時" ASC
    ) AS "在庫数_前回",
    "フリー在庫数",
    LAG("フリー在庫数") OVER (
        PARTITION BY "商品コード" 
        ORDER BY "記録日時" ASC
    ) AS "フリー在庫数_前回"
FROM 
    "NE_InventoryHistory"
WHERE 
    "商品コード" IN ('A001', 'もう一つ別のテスト用商品コード') -- ※実在する別コードに差し替えてください
ORDER BY 
    "商品コード" ASC,
    "記録日時" ASC; -- ※商品ごとに並べた上で、時間の古い順に並べ替えます